import 'package:flutter/material.dart';
import 'package:google_fonts/google_fonts.dart';
import 'package:firebase_auth/firebase_auth.dart';
import 'package:cloud_firestore/cloud_firestore.dart';
import 'package:image_picker/image_picker.dart';
import 'dart:io';
import 'dart:convert';
import 'package:http/http.dart' as http;

import 'complaint_model.dart';

class ComplaintPage extends StatefulWidget {
  const ComplaintPage({super.key});

  @override
  State<ComplaintPage> createState() => _ComplaintPageState();
}

class _ComplaintPageState extends State<ComplaintPage> {
  final _formKey = GlobalKey<FormState>();
  final FirebaseAuth _auth = FirebaseAuth.instance;
  final FirebaseFirestore _firestore = FirebaseFirestore.instance;

  // Complaint types
  final List<String> _complaintTypes = [
    'Food Quality Issue',
    'Delivery Problem',
    'Order Missing/Incomplete',
    'Payment Issue',
    'App Technical Issue',
    'Restaurant Service',
    'Hygiene Concern',
    'Billing Problem',
    'Other'
  ];

  // Form controllers
  late TextEditingController _titleController;
  late TextEditingController _descriptionController;
  String _selectedComplaintType = 'Food Quality Issue';

  // Image handling
  List<File> _selectedImages = [];
  List<String> _uploadedImageUrls = [];
  bool _isUploading = false;
  bool _isSubmitting = false;

  // ImageKit configuration
  final String _privateApiKey = 'private_u6KRAwruwE6w8xR63Vl7enrhpzk=';
  final String _uploadEndpoint = 'https://upload.imagekit.io/api/v1/files/upload';

  @override
  void initState() {
    super.initState();
    _titleController = TextEditingController();
    _descriptionController = TextEditingController();
  }

  @override
  void dispose() {
    _titleController.dispose();
    _descriptionController.dispose();
    super.dispose();
  }

  Future<void> _pickImages() async {
    final picker = ImagePicker();
    final pickedFiles = await picker.pickMultiImage(
      imageQuality: 80,
      maxWidth: 800,
    );

    if (pickedFiles.isNotEmpty) {
      setState(() {
        _selectedImages.addAll(pickedFiles.map((file) => File(file.path)));
      });
    }
  }

  Future<String?> _uploadImageToImageKit(File image) async {
    try {
      final bytes = await image.readAsBytes();
      final base64Image = base64Encode(bytes);

      final response = await http.post(
        Uri.parse(_uploadEndpoint),
        headers: {
          'Authorization': 'Basic ${base64Encode(utf8.encode('$_privateApiKey:'))}',
        },
        body: {
          'file': base64Image,
          'fileName': 'complaint_${DateTime.now().millisecondsSinceEpoch}.jpg',
          'useUniqueFileName': 'true',
          'folder': '/complaints', // Store in complaints folder
        },
      );

      if (response.statusCode == 200) {
        final data = jsonDecode(response.body);
        return data['url']; // Return the ImageKit URL
      } else {
        print('❌ Image upload failed: ${response.body}');
        return null;
      }
    } catch (e) {
      print('❌ Error uploading image: $e');
      return null;
    }
  }

  Future<void> _uploadAllImages() async {
    setState(() => _isUploading = true);
    _uploadedImageUrls.clear();

    for (final image in _selectedImages) {
      final imageUrl = await _uploadImageToImageKit(image);
      if (imageUrl != null) {
        _uploadedImageUrls.add(imageUrl);
      }
    }

    setState(() => _isUploading = false);
  }

  Future<Map<String, dynamic>> _getUserData() async {
    final user = _auth.currentUser;
    if (user == null) throw Exception('User not authenticated');

    // Try to get user name from address collection
    final addressDoc = await _firestore
        .collection('users')
        .doc(user.uid)
        .collection('Address')
        .doc('default')
        .get();

    String userName = 'Guest';
    if (addressDoc.exists && addressDoc['name'] != null) {
      userName = addressDoc['name'];
    } else {
      // Fallback to user document
      final userDoc = await _firestore.collection('users').doc(user.uid).get();
      if (userDoc.exists && userDoc['name'] != null) {
        userName = userDoc['name'];
      }
    }

    return {
      'userId': user.uid,
      'userName': userName,
      'userEmail': user.email ?? 'No Email',
    };
  }

  Future<void> _submitComplaint() async {
    if (!_formKey.currentState!.validate()) return;

    setState(() => _isSubmitting = true);

    try {
      // Upload images first
      if (_selectedImages.isNotEmpty) {
        await _uploadAllImages();
      }

      // Get user data
      final userData = await _getUserData();

      // Create complaint object
      final complaint = Complaint(
        id: '', // Will be generated by Firestore
        userId: userData['userId'],
        userName: userData['userName'],
        userEmail: userData['userEmail'],
        complaintType: _selectedComplaintType,
        title: _titleController.text.trim(),
        description: _descriptionController.text.trim(),
        imageUrls: _uploadedImageUrls,
        status: 'Pending',
        createdAt: DateTime.now(),
      );

      // Save to Firestore
      final docRef = await _firestore
          .collection('users')
          .doc(userData['userId'])
          .collection('complaints')
          .add(complaint.toMap());

      ScaffoldMessenger.of(context).showSnackBar(
        SnackBar(
          content: Text(
            'Complaint submitted successfully!',
            style: GoogleFonts.poppins(color: Colors.white),
          ),
          backgroundColor: Colors.green,
          duration: Duration(seconds: 3),
        ),
      );

      // Reset form
      _formKey.currentState!.reset();
      setState(() {
        _selectedImages.clear();
        _uploadedImageUrls.clear();
        _selectedComplaintType = 'Food Quality Issue';
      });

    } catch (e) {
      ScaffoldMessenger.of(context).showSnackBar(
        SnackBar(
          content: Text(
            'Error submitting complaint: $e',
            style: GoogleFonts.poppins(color: Colors.white),
          ),
          backgroundColor: Colors.red,
        ),
      );
    } finally {
      setState(() => _isSubmitting = false);
    }
  }

  void _removeImage(int index) {
    setState(() {
      _selectedImages.removeAt(index);
    });
  }

  void _showFullScreenImage(File image) {
    showDialog(
      context: context,
      builder: (context) => Dialog(
        backgroundColor: Colors.transparent,
        child: Stack(
          children: [
            Center(
              child: Image.file(image),
            ),
            Positioned(
              top: 40,
              right: 20,
              child: IconButton(
                icon: Icon(Icons.close, color: Colors.white, size: 30),
                onPressed: () => Navigator.pop(context),
              ),
            ),
          ],
        ),
      ),
    );
  }


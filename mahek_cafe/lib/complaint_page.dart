                    return 'Description should be at least 10 characters long';
                  }
                  return null;
                },
              ),
              const SizedBox(height: 20),

              // Image Upload Section
              Row(
                children: [
                  Text(
                    'Attach Images',
                    style: GoogleFonts.poppins(
